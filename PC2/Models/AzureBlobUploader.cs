using Azure;
using Azure.Identity;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;
using Microsoft.AspNetCore.Http;
using Microsoft.Extensions.Azure;
using Microsoft.Net.Http.Headers;
using System;
using System.IO;
using System.Text.RegularExpressions;
using System.Threading.Tasks;

namespace PC2.Models
{
    /// <summary>
    /// Helper class to upload files to Azure Blob Storage.
    /// </summary>
    public partial class AzureBlobUploader
    {
        /// <summary>
        /// Every PDF gets a new blob name, so its contents never change and browsers can cache it for a year
        /// </summary>
        private const string ImmutableCacheControl = "public, max-age=31536000, immutable";

        private const int MaxReadableNameLength = 80;

        private readonly BlobContainerClient _containerClient;
        private bool _containerExists;

        public AzureBlobUploader(IConfiguration configuration)
        {
            // Clients are thread-safe, and this class is a singleton, so they are created once
            _containerClient = CreateBlobServiceClient(configuration)
                .GetBlobContainerClient(configuration["AzureBlob:ContainerName"]);
        }

        /// <summary>
        /// Uploads an IFormFile to Azure Blob Storage and returns the blob URL.
        /// </summary>
        /// <param name="file">The file to upload.</param>
        /// <param name="blobName">The name to use for the blob in storage. It must be generated by the server, never taken from the upload.</param>
        /// <param name="contentType">
        /// Content type to serve the blob with. Only pass one the server has verified, never the
        /// browser-supplied IFormFile.ContentType. Without one, Azure serves application/octet-stream.
        /// </param>
        /// <returns>The URL of the uploaded blob.</returns>
        public async Task<string> UploadFileAsync(IFormFile file, string blobName, string? contentType = null)
        {
            if (!IsSafeBlobName(blobName))
                throw new ArgumentException($"\"{blobName}\" is not a valid blob name.", nameof(blobName));

            // No conditions, so an existing blob with this name is overwritten
            return await UploadAsync(file, blobName, new BlobUploadOptions
            {
                HttpHeaders = new BlobHttpHeaders { ContentType = contentType }
            });
        }

        /// <summary>
        /// Uploads a PDF under a new, unique blob name and returns the blob URL. It is served as a PDF
        /// that browsers download under the original file name. Check it with <see cref="PdfFileValidator"/> first.
        /// </summary>
        /// <param name="file">The PDF to upload.</param>
        /// <returns>The URL of the uploaded blob.</returns>
        public async Task<string> UploadPdfAsync(IFormFile file)
        {
            string fileName = GetFileName(file.FileName);
            string blobName = CreateUniqueBlobName(fileName, ".pdf");

            string downloadName = fileName.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase) ? fileName : blobName;
            ContentDispositionHeaderValue disposition = new("attachment");
            disposition.SetHttpFileName(downloadName);

            return await UploadAsync(file, blobName, new BlobUploadOptions
            {
                HttpHeaders = new BlobHttpHeaders
                {
                    ContentType = "application/pdf",
                    ContentDisposition = disposition.ToString(),
                    CacheControl = ImmutableCacheControl
                },
                // Never replace an existing blob
                Conditions = new BlobRequestConditions { IfNoneMatch = ETag.All }
            });
        }

        /// <summary>
        /// Deletes a file (blob) from Azure Blob Storage.
        /// </summary>
        /// <param name="blobName">The name of the blob to delete, as it appears at the end of its URL.</param>
        /// <returns>True if the blob was deleted, false if it did not exist.</returns>
        public async Task<bool> DeleteFileAsync(string blobName)
        {
            // Decode the blob name to match the expected format in Azure Blob Storage
            blobName = Uri.UnescapeDataString(blobName);
            if (!IsSafeBlobName(blobName))
                return false;

            var response = await _containerClient.GetBlobClient(blobName).DeleteIfExistsAsync();
            return response.Value;
        }

        /// <summary>
        /// Opens a stored file (blob) for reading.
        /// </summary>
        /// <param name="blobUrl">The URL returned by <see cref="UploadFileAsync"/> or <see cref="UploadPdfAsync"/> when the file was uploaded.</param>
        /// <returns>A read-only stream of the file, or null if it no longer exists.</returns>
        public async Task<Stream?> OpenReadAsync(string blobUrl)
        {
            string? blobName = blobUrl.Split('/').LastOrDefault();
            if (string.IsNullOrEmpty(blobName))
                return null;

            // Decode the blob name to match the expected format in Azure Blob Storage
            blobName = Uri.UnescapeDataString(blobName);
            if (!IsSafeBlobName(blobName))
                return null;

            try
            {
                return await _containerClient.GetBlobClient(blobName).OpenReadAsync();
            }
            catch (RequestFailedException ex) when (ex.Status == StatusCodes.Status404NotFound)
            {
                return null;
            }
        }

        /// <summary>
        /// Builds a new blob name from an uploaded file's name, e.g. "Fall Newsletter.pdf" becomes
        /// "Fall-Newsletter-3f2a9c1b8d7e.pdf". The random part keeps uploads with the same name from
        /// replacing each other, and the readable part keeps the file recognizable in storage and analytics.
        /// </summary>
        /// <param name="fileName">The name of the uploaded file. Any folder path in it is ignored.</param>
        /// <param name="extension">The extension to give the blob, including the dot, e.g. ".pdf"</param>
        public static string CreateUniqueBlobName(string? fileName, string extension)
        {
            string readableName = Path.GetFileNameWithoutExtension(GetFileName(fileName));
            readableName = UnsafeBlobNameCharacters().Replace(readableName, "-").Trim('-', '.');
            if (readableName.Length > MaxReadableNameLength)
            {
                readableName = readableName[..MaxReadableNameLength].TrimEnd('-', '.');
            }
            if (readableName.Length == 0)
            {
                readableName = "file";
            }

            return $"{readableName}-{Guid.NewGuid().ToString("N")[..12]}{extension}";
        }

        /// <summary>
        /// True if the name refers to a blob directly inside the container: not empty, no folder
        /// separators, and not "." or "..", which would point outside it.
        /// </summary>
        public static bool IsSafeBlobName(string? blobName)
        {
            return !string.IsNullOrWhiteSpace(blobName)
                && blobName.IndexOfAny(['/', '\\']) < 0
                && blobName != "."
                && blobName != "..";
        }

        /// <summary>
        /// The file name without any folder path. Some browsers send the full path of the uploaded file.
        /// </summary>
        private static string GetFileName(string? fileName)
        {
            if (string.IsNullOrEmpty(fileName))
                return string.Empty;

            return fileName[(fileName.LastIndexOfAny(['/', '\\']) + 1)..].Trim();
        }

        private async Task<string> UploadAsync(IFormFile file, string blobName, BlobUploadOptions options)
        {
            if (file == null || file.Length == 0)
                throw new ArgumentException("File is null or empty.");

            if (!_containerExists)
            {
                await _containerClient.CreateIfNotExistsAsync(PublicAccessType.Blob);
                _containerExists = true;
            }

            var blobClient = _containerClient.GetBlobClient(blobName);

            // The caller owns the stream lifetime
            var stream = file.OpenReadStream();
            await blobClient.UploadAsync(stream, options);

            return blobClient.Uri.ToString();
        }

        private static BlobServiceClient CreateBlobServiceClient(IConfiguration configuration)
        {
#if DEBUG
            return new BlobServiceClient(configuration["AzureBlob:BlobServiceUri"]);
#else
            return new BlobServiceClient(new Uri(configuration["AzureBlob:BlobServiceUri"]), new DefaultAzureCredential());
#endif
        }

        /// <summary>
        /// Anything other than letters, digits, dots, dashes and underscores
        /// </summary>
        [GeneratedRegex(@"[^A-Za-z0-9._-]+")]
        private static partial Regex UnsafeBlobNameCharacters();
    }
}
